-- Target schema: proper types, NOT NULL, CHECK, UNIQUE, FOREIGN KEYS.
-- Portable between PostgreSQL 12+ and H2 2.x (MODE=PostgreSQL).

CREATE TABLE customers (
    id                INTEGER      PRIMARY KEY,
    email             VARCHAR(255) NOT NULL,
    email_normalized  VARCHAR(255) NOT NULL,
    full_name         VARCHAR(255) NOT NULL,
    phone             VARCHAR(50),
    created_at        TIMESTAMP    NOT NULL,
    -- Case-insensitive uniqueness without functional indexes (portable): store the lowered value and enforce it
    CONSTRAINT uq_customers_email_normalized UNIQUE (email_normalized),
    CONSTRAINT ck_customers_email_normalized CHECK (email_normalized = LOWER(email)),
    CONSTRAINT ck_customers_email_format CHECK (email LIKE '%_@_%._%')
);

CREATE TABLE products (
    id     INTEGER       PRIMARY KEY,
    sku    VARCHAR(50)   NOT NULL,
    name   VARCHAR(255)  NOT NULL,
    price  NUMERIC(10,2) NOT NULL,
    CONSTRAINT uq_products_sku UNIQUE (sku),
    CONSTRAINT ck_products_price CHECK (price >= 0)
);

CREATE TABLE orders (
    id           INTEGER       PRIMARY KEY,
    customer_id  INTEGER       NOT NULL,
    order_date   TIMESTAMP     NOT NULL,
    status       VARCHAR(20)   NOT NULL,
    total        NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT ck_orders_status CHECK (status IN ('NEW', 'PAID', 'SHIPPED', 'CANCELLED')),
    CONSTRAINT ck_orders_total CHECK (total >= 0)
);

CREATE TABLE order_items (
    id          INTEGER       PRIMARY KEY,
    order_id    INTEGER       NOT NULL,
    product_id  INTEGER       NOT NULL,
    quantity    INTEGER       NOT NULL,
    unit_price  NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_items_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_items_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_items_unit_price CHECK (unit_price >= 0)
);

-- Which legacy customer id ended up as which new customer (duplicates are merged into the lowest id)
CREATE TABLE legacy_customer_map (
    legacy_customer_id  INTEGER PRIMARY KEY,
    customer_id         INTEGER NOT NULL,
    CONSTRAINT fk_map_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
);

-- Quarantine: every legacy row that was NOT migrated as-is, with a machine-readable reason
CREATE TABLE migration_rejects (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_table  VARCHAR(50)   NOT NULL,
    source_id     INTEGER       NOT NULL,
    reason        VARCHAR(50)   NOT NULL,
    payload       VARCHAR(1000),
    rejected_at   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_rejects_source UNIQUE (source_table, source_id)
);
